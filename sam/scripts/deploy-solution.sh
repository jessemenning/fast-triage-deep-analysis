#!/usr/bin/env bash
# Deploy a solution that SolutionBuilder generated.
#
# SolutionBuilder saves each generated component as an artifact whose content
# is a declarative `kind:` YAML (kind: entrypoint | workflow | agent |
# connector | model). This script collects those files into
# solutions/<name>/<plural-kind>/, writes solutions/<name>/manifests/dev.yaml
# if it does not exist yet, then runs `sam config plan` + `sam config apply`.
#
# Usage:
#   scripts/deploy-solution.sh <name> [source-dir] [--all] [--plan-only]
#
#   <name>       solution slug (e.g. arrival-capacity). Also used as a filter:
#                only files whose path or content mentions <name> are copied,
#                unless --all is given.
#   source-dir   where to look for kind: YAML. Default: the platform's
#                artifact store ($SAM_HOME/data/artifacts, i.e.
#                ~/.config/sam/data/artifacts). Pass a directory you exported
#                or downloaded from the chat UI instead if you prefer.
#   --all        copy every kind: YAML found under source-dir (no name filter)
#   --plan-only  stop after plan
set -euo pipefail
cd "$(dirname "$0")/.."

if [[ -f .env ]]; then
  set -a
  # shellcheck disable=SC1091
  . ./.env
  set +a
fi

# This repo pins SAM CLI 2.403.3 (matches the runtime image + the Makefile `SAM` var).
# Override with SAM=... (e.g. SAM=sam-2.380.0 for the one-line rollback).
SAM="${SAM:-sam-2.403.3}"
command -v "$SAM" >/dev/null 2>&1 || SAM="$HOME/.local/bin/${SAM##*/}"

NAME="${1:-}"
[[ -n "$NAME" ]] || { echo "usage: $0 <name> [source-dir] [--all] [--plan-only]" >&2; exit 2; }
shift

SRC="${SAM_HOME:-$HOME/.config/sam}/data/artifacts"
ALL=0
PLAN_ONLY=0
for arg in "$@"; do
  case "$arg" in
    --all)       ALL=1 ;;
    --plan-only) PLAN_ONLY=1 ;;
    *)           SRC="$arg" ;;
  esac
done
[[ -d "$SRC" ]] || { echo "error: source dir not found: $SRC" >&2; exit 2; }

DEST="solutions/$NAME"
mkdir -p "$DEST/manifests"

plural_for() {
  case "$1" in
    agent)      echo agents ;;
    workflow)   echo workflows ;;
    entrypoint) echo entrypoints ;;
    connector)  echo connectors ;;
    model)      echo models ;;
    *)          echo "" ;;
  esac
}

declare -A RES   # plural -> newline-separated names
copied=0
while IFS= read -r -d '' f; do
  kind="$(grep -m1 -E '^kind:' "$f" | sed -E 's/^kind:[[:space:]]*"?([a-zA-Z_]+)"?.*/\1/')"
  [[ -n "$kind" ]] || continue
  plural="$(plural_for "$kind")"
  [[ -n "$plural" ]] || { echo "skip (kind $kind not deployable here): $f" >&2; continue; }
  if [[ $ALL -eq 0 ]] && ! { grep -qi -- "$NAME" "$f" || [[ "$f" == *"$NAME"* ]]; }; then
    continue
  fi
  # resource name: top-level `name:`; models fall back to spec.alias
  rname="$(grep -m1 -E '^name:' "$f" | sed -E 's/^name:[[:space:]]*"?([^"]*)"?[[:space:]]*$/\1/')"
  if [[ -z "$rname" && "$kind" == "model" ]]; then
    rname="$(grep -m1 -E '^[[:space:]]+alias:' "$f" | sed -E 's/^[[:space:]]+alias:[[:space:]]*"?([^"]*)"?[[:space:]]*$/\1/')"
  fi
  [[ -n "$rname" ]] || { echo "skip (no name:): $f" >&2; continue; }
  mkdir -p "$DEST/$plural"
  cp -f -- "$f" "$DEST/$plural/$rname.yaml"
  RES[$plural]+="$rname"$'\n'
  copied=$((copied + 1))
  echo "copied $kind '$rname' <- $f"
done < <(find "$SRC" -type f \( -name '*.yaml' -o -name '*.yml' \) -print0)

if [[ $copied -eq 0 ]]; then
  echo "error: no kind: YAML matching '$NAME' found under $SRC (try --all or pass a source dir)" >&2
  exit 1
fi

MANIFEST="$DEST/manifests/dev.yaml"
if [[ ! -f "$MANIFEST" ]]; then
  {
    echo "kind: manifest"
    echo "name: $NAME"
    echo "description: \"Solution '$NAME' generated by SolutionBuilder — deployed to the embedded platform at localhost:8800\""
    echo "target:"
    echo "  url: \"http://127.0.0.1:8800\""
    echo "  auth:"
    echo "    type: bearer_token"
    echo "    envVar: SAM_PLATFORM_TOKEN"
    echo "resources:"
    for plural in models connectors agents workflows entrypoints; do
      [[ -n "${RES[$plural]:-}" ]] || continue
      echo "  $plural:"
      printf '%s' "${RES[$plural]}" | sort -u | while IFS= read -r n; do
        [[ -n "$n" ]] && echo "    - \"$n\""
      done
    done
  } >"$MANIFEST"
  echo "wrote $MANIFEST"
else
  echo "keeping existing $MANIFEST (edit it if new resources were added)"
fi

echo
echo "==> $SAM config plan --manifest $MANIFEST"
"$SAM" config plan --manifest "$MANIFEST"
[[ $PLAN_ONLY -eq 1 ]] && exit 0

echo
echo "==> $SAM config apply --manifest $MANIFEST"
"$SAM" config apply --manifest "$MANIFEST"
