#!/usr/bin/env python3
"""
gen_sample_corpus.py — generate a deterministic, offline sample corpus for the demo.

Produces stack/data/sample-corpus.jsonl in replay.py's record format. The baseline it
creates keeps every airport's rolling-hour arrival demand BELOW its published AAR, so
nothing breaches until the scenario driver degrades the hero airport. Re-run to
regenerate; commit the output so `make up` works with no live SWIM feed.

Rates/ETAs/weather use now-relative tokens ("@now", "@+<seconds>") that replay.py
rewrites at publish time, so the canned data always lands in Feldera's live window.
"""
import json
import os
import random

random.seed(42)

OUT = os.path.join(os.path.dirname(__file__), "sample-corpus.jsonl")

# airport -> (normal AAR, normal ADR, runway_config, baseline inbound count/hour)
# baseline inbound is kept comfortably under AAR so the baseline never breaches.
AIRPORTS = {
    "KMKG": (30, 30, "06|24",    22),
    "KEWR": (44, 44, "22L|22R",  34),
    "KJFK": (44, 44, "31L|31R",  30),
    "KLGA": (40, 40, "22|13",    22),
    "KPHL": (48, 48, "27L|27R",  20),
    "KBOS": (44, 44, "04R|04L",  18),
    "KORD": (96, 96, "10C|10L",  40),
    "KATL": (120,120, "26R|27L", 45),
    "KDCA": (36, 36, "01|19",    16),
    "KIAD": (60, 60, "01C|01R",  20),
    "KBWI": (48, 48, "15R|33L",  18),
}
ORIGINS = ["KSFO", "KLAX", "KDEN", "KDFW", "KMIA", "KSEA", "KMCO", "KCLT", "KMSP", "KSLC"]
CARRIERS = ["UAL", "AAL", "DAL", "JBU", "SWA", "ASA", "NKS", "FFT"]


def callsign():
    return random.choice(CARRIERS) + str(random.randint(100, 9999))


def gufi(n):
    return f"GUFI{n:06d}"


def main():
    records = []
    n = 0

    # 1) current published rates (effective now) for every airport
    for apt, (aar, adr, cfg, _) in AIRPORTS.items():
        records.append({
            "delay": 0.05,
            "topic": f"TTP/airportInfo/{apt}",
            "payload": {"airport": apt, "aar": aar, "adr": adr,
                        "runway_config": cfg, "effective_time": "@now"},
        })

    # 2) baseline METAR (VFR) per airport
    for apt in AIRPORTS:
        records.append({
            "delay": 0.05,
            "topic": f"aviation/metar/{apt}",
            "payload": {"icaoId": apt, "reportTime": "@now", "fltCat": "VFR",
                        "wdir": str(random.choice([180, 200, 220, 240])),
                        "wspd": random.randint(4, 12), "visib": "10+",
                        "rawOb": f"{apt} VFR wind calm vis 10SM"},
        })

    # 3) inbound flights: flightplan + TTPFD eta (+ a position for the map)
    flights = []
    for apt, (_, _, _, inbound) in AIRPORTS.items():
        for _ in range(inbound):
            n += 1
            flights.append((n, apt))
    random.shuffle(flights)

    for num, apt in flights:
        cs = callsign()
        g = gufi(num)
        origin = random.choice(ORIGINS)
        eta_off = random.randint(0, 3600)            # arrival within the next hour
        src = random.choices(["TTPFD", "TBFM", "FILED"], weights=[55, 25, 20])[0]
        lat = round(random.uniform(38.5, 42.5), 4)
        lon = round(random.uniform(-80.0, -71.0), 4)

        records.append({
            "delay": round(random.uniform(0.08, 0.22), 3),
            "topic": f"FDPS/flightPlan/{cs}/ACTIVE/{origin}/{apt}/{g}",
            "payload": {"flight_id": cs, "status": "ACTIVE", "departure": origin,
                        "arrival": apt, "gufi": g},
        })
        records.append({
            "delay": round(random.uniform(0.05, 0.15), 3),
            "topic": f"TTP/flightData/{g}/{apt}/{src}",
            "payload": {"gufi": g, "arrival": apt, "eta": f"@+{eta_off}", "eta_source": src},
        })
        records.append({
            "delay": round(random.uniform(0.02, 0.08), 3),
            "topic": (f"FDPS/position/{cs}/ACTIVE/{cs}/{origin}/{apt}/"
                      f"{lat}/{lon}/{random.randint(240, 460)}/"
                      f"{random.choice([28000, 32000, 36000, 12000, 9000])}/"
                      f"{random.randint(0, 359)}/{g}"),
            "payload": {"flight_id": cs, "gufi": g},
        })

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("# faa-fast-slow sample corpus — generated by gen_sample_corpus.py\n")
        for r in records:
            fh.write(json.dumps(r) + "\n")

    total_delay = sum(r["delay"] for r in records)
    print(f"wrote {len(records)} records to {OUT} (~{total_delay:.0f}s per replay pass)")


if __name__ == "__main__":
    main()
